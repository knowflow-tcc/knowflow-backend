-- =====================================================================
-- KnowFlow - Fluxo do Conhecimento
-- Script de criação do banco no PostgreSQL 16 (RNF14)
--
-- 15 tabelas: as 8 entidades do DER (seção 3.3), a tabela de ligação
-- problema_palavra_chave (relação N:N) e as 6 tabelas dos requisitos
-- desejáveis (RF14, RF16, RF17, RF18, RF21, RF24).
--
-- Gerado a partir das entidades JPA (pacote model) e organizado à mão.
-- A aplicação também cria/atualiza as tabelas sozinha
-- (spring.jpa.hibernate.ddl-auto=update); este script serve para criar o
-- banco manualmente pelo pgAdmin e para documentar o modelo físico.
--
-- Como usar (pgAdmin): crie o banco "fluxoconhecimento", abra o
-- Query Tool nele, cole este arquivo e execute (F5).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Entidades do DER (seção 3.3 do TCC)
-- ---------------------------------------------------------------------

-- Setores da empresa (RF03)
create table departamento (
    id          bigint generated by default as identity primary key,
    nome        varchar(100) not null unique,
    descricao   varchar(500)
);

-- Dados de acesso e perfil (RF01, RF02, RN02, RN03, RNF01)
-- ativo: desativação (RF02) e RN01 - usuário nunca é excluído
create table usuario (
    id               bigint generated by default as identity primary key,
    nome             varchar(120) not null,
    email            varchar(150) not null unique,              -- RN02
    senha_hash       varchar(100) not null,                     -- RNF01 (BCrypt)
    perfil           varchar(20)  not null
                     check (perfil in ('COLABORADOR', 'GESTOR', 'ADMINISTRADOR')),  -- RN03
    ativo            boolean not null,
    id_departamento  bigint  not null,                          -- RN03
    constraint fk_usuario_departamento foreign key (id_departamento) references departamento
);

-- Classificação em árvore: categoria e subcategorias (RF07, seção 3.2)
create table categoria (
    id                bigint generated by default as identity primary key,
    nome              varchar(80) not null,
    id_categoria_pai  bigint,
    constraint fk_categoria_pai foreign key (id_categoria_pai) references categoria
);

-- Situação registrada (RF04, RF15, RF23, RN04, RN09)
create table problema (
    id               bigint generated by default as identity primary key,
    titulo           varchar(150)  not null,                    -- RN04
    descricao        varchar(5000) not null,                    -- RN04
    data_registro    timestamp(6)  not null,
    status           varchar(20)   not null check (status in ('ABERTO', 'RESOLVIDO')),  -- RF23
    ativo            boolean       not null,                    -- RN09 (arquivado = false)
    id_usuario       bigint not null,
    id_departamento  bigint not null,                           -- RN04
    id_categoria     bigint not null,                           -- RN04
    constraint fk_problema_usuario      foreign key (id_usuario)      references usuario,
    constraint fk_problema_departamento foreign key (id_departamento) references departamento,
    constraint fk_problema_categoria    foreign key (id_categoria)    references categoria
);

-- Termos de busca (RF07)
create table palavra_chave (
    id     bigint generated by default as identity primary key,
    termo  varchar(40) not null unique
);

-- Relação N:N problema x palavra-chave
create table problema_palavra_chave (
    id_problema       bigint not null,
    id_palavra_chave  bigint not null,
    primary key (id_palavra_chave, id_problema),
    constraint fk_ppc_problema      foreign key (id_problema)      references problema,
    constraint fk_ppc_palavra_chave foreign key (id_palavra_chave) references palavra_chave
);

-- Causas de um problema (RF05, RN05, RNF07)
create table causa (
    id           bigint generated by default as identity primary key,
    descricao    varchar(5000) not null,
    ativo        boolean not null,                              -- RN09
    id_problema  bigint  not null,                              -- RN05
    id_usuario   bigint  not null,
    constraint fk_causa_problema foreign key (id_problema) references problema,
    constraint fk_causa_usuario  foreign key (id_usuario)  references usuario
);

-- Soluções de um problema (RF06, RF10, RN05, RN07, RN08, RNF07)
create table solucao (
    id             bigint generated by default as identity primary key,
    descricao      varchar(5000) not null,
    validada       boolean      not null,                       -- RF10
    data_registro  timestamp(6) not null,
    ativo          boolean      not null,                       -- RN09
    id_problema    bigint not null,                             -- RN05
    id_usuario     bigint not null,
    constraint fk_solucao_problema foreign key (id_problema) references problema,
    constraint fk_solucao_usuario  foreign key (id_usuario)  references usuario
);

-- Registro das alterações (RF11, RN10)
-- id_registro: qual linha de tabela_afetada sofreu a ação
create table historico (
    id              bigint generated by default as identity primary key,
    acao            varchar(20) not null check (acao in ('INCLUSAO', 'ALTERACAO', 'ARQUIVAMENTO', 'VALIDACAO',
                                                         'DESATIVACAO', 'REATIVACAO', 'ANONIMIZACAO')),
    data_hora       timestamp(6) not null,
    tabela_afetada  varchar(30)  not null,
    id_registro     bigint       not null,
    id_usuario      bigint       not null,
    constraint fk_historico_usuario foreign key (id_usuario) references usuario
);
create index idx_historico_registro on historico (tabela_afetada, id_registro);

-- ---------------------------------------------------------------------
-- Requisitos desejáveis
-- ---------------------------------------------------------------------

-- RF16 - anexos de problemas OU de soluções (o arquivo fica no próprio banco)
create table anexo (
    id             bigint generated by default as identity primary key,
    nome_arquivo   varchar(255) not null,
    tipo_conteudo  varchar(100) not null,
    tamanho        bigint       not null,
    conteudo       bytea        not null,
    data_hora      timestamp(6) not null,
    ativo          boolean      not null,                       -- RN09
    id_problema    bigint,
    id_solucao     bigint,
    id_usuario     bigint not null,
    constraint ck_anexo_problema_ou_solucao check ((id_problema is null) <> (id_solucao is null)),
    constraint fk_anexo_problema foreign key (id_problema) references problema,
    constraint fk_anexo_solucao  foreign key (id_solucao)  references solucao,
    constraint fk_anexo_usuario  foreign key (id_usuario)  references usuario
);

-- RF17 - comentários em soluções
create table comentario (
    id          bigint generated by default as identity primary key,
    texto       varchar(2000) not null,
    data_hora   timestamp(6)  not null,
    ativo       boolean       not null,                         -- RN09
    id_solucao  bigint not null,
    id_usuario  bigint not null,
    constraint fk_comentario_solucao foreign key (id_solucao) references solucao,
    constraint fk_comentario_usuario foreign key (id_usuario) references usuario
);

-- RF18 - "esta solução me ajudou" (um voto por usuário e solução)
create table avaliacao_solucao (
    id          bigint generated by default as identity primary key,
    ajudou      boolean      not null,
    data_hora   timestamp(6) not null,
    id_solucao  bigint not null,
    id_usuario  bigint not null,
    constraint uk_avaliacao_usuario_solucao unique (id_usuario, id_solucao),
    constraint fk_avaliacao_solucao foreign key (id_solucao) references solucao,
    constraint fk_avaliacao_usuario foreign key (id_usuario) references usuario
);

-- RF21 - notificações ao autor da solução (validada ou comentada)
create table notificacao (
    id           bigint generated by default as identity primary key,
    mensagem     varchar(300) not null,
    lida         boolean      not null,
    data_hora    timestamp(6) not null,
    id_usuario   bigint not null,                               -- destinatário
    id_problema  bigint not null,
    constraint fk_notificacao_usuario  foreign key (id_usuario)  references usuario,
    constraint fk_notificacao_problema foreign key (id_problema) references problema
);
create index idx_notificacao_usuario on notificacao (id_usuario, lida);

-- RF24 - problemas favoritos de cada usuário
create table favorito (
    id           bigint generated by default as identity primary key,
    data_hora    timestamp(6) not null,
    id_usuario   bigint not null,
    id_problema  bigint not null,
    constraint uk_favorito_usuario_problema unique (id_usuario, id_problema),
    constraint fk_favorito_usuario  foreign key (id_usuario)  references usuario,
    constraint fk_favorito_problema foreign key (id_problema) references problema
);

-- RF14 - links de recuperação de senha (guardados só como hash SHA-256)
create table token_recuperacao_senha (
    id          bigint generated by default as identity primary key,
    token_hash  varchar(64)  not null unique,
    expira_em   timestamp(6) not null,
    usado       boolean      not null,
    id_usuario  bigint not null,
    constraint fk_token_usuario foreign key (id_usuario) references usuario
);

